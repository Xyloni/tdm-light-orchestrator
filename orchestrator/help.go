func commandHelp(key string) string {
	key = strings.ToLower(key)
	if key == "" {
		return commands
	}
	for _, topic := range helpTopics {
		if topic.Key == key {
			return topic.Title + "\n\n" + topic.Body
		}
	}
	return "Раздел справки не найден.\n\n" + commands
}
